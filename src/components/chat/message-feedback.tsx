export default function MessageFeedback({ onFeedback, id }: FeedbackProps) {
    const [like, setlike] = useState(false);
    const [dislike, setDislike] = useState(false);

    const [showTip, setShowTip] = useState(false);

    console.log(id)

    const { run: handleClick } = useDebounceFn((type: "like" | "dislike") => {
        const val = type === "like" ? !like : !dislike;
        if (type === "like") {
            setlike(val);
        } else {
            setDislike(val);
        }
        setShowTip(true);
        onFeedback?.(type);
        setTimeout(() => setShowTip(false), 1500);
    }, {
        wait: 800,
        leading: true,
    });

    return (
        <div className="flex items-center bg-[#faf9f8] px-0.5 rounded-lg">
            <button
                className="p-2"
                onClick={() => handleClick("like")}
                aria-label="赞同"
            >
                <Icon isFill={like} />
            </button>
            <span className="border-r border-[#e5d9c2] h-2.5 inline-block" />
            <button
                className="p-2"
                onClick={() => handleClick("dislike")}
                aria-label="不赞同"
            >
                <Icon isFill={dislike} isUnlikeIcon />
            </button>
            {showTip && (
                <>
                    {/* 遮罩层 */}
                    {/* <div className="fixed inset-0 w-screen h-screen z-[9998] bg-transparent animate-fade-in-out" /> */}
                    {/* 居中tip */}
                    <span className="fixed text-sm left-1/2 top-1/2 z-[9999] -translate-x-1/2 -translate-y-1/2 px-6 py-3 rounded-[8px] bg-[#393f4c] text-white font-medium shadow-lg animate-fade-in-out select-none">感谢你的反馈～</span>
                </>
            )}
        </div>
    );
}
